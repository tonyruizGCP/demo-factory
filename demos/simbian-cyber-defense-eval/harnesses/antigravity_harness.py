def normalize_detection(data: Dict[str, Any]) -> AgentDetection:
    """Safely normalize LLM detection dictionary into AgentDetection model.

    Args:
        data (Dict[str, Any]): Raw JSON output generated by LLM or simulated engine.

    Returns:
        AgentDetection: Validated Pydantic model with normalized MITRE tactic enum and confidence float.
    """
    tactic_str = str(data.get("tactic", "")).strip().lower().replace(" ", "-").replace("_", "-")
    matched_tactic = MitreTactic.EXECUTION
    for t in MitreTactic:
        if t.value == tactic_str or t.value.replace("-", "") == tactic_str.replace("-", ""):
            matched_tactic = t
            break

    conf_raw = data.get("confidence", 0.95)
    if isinstance(conf_raw, (int, float)):
        conf = float(conf_raw)
    else:
        s = str(conf_raw).strip().lower()
        if "high" in s:
            conf = 0.95
        elif "med" in s:
            conf = 0.80
        elif "low" in s:
            conf = 0.50
        else:
            try:
                conf = float(s)
            except Exception:
                conf = 0.90

    evidence = data.get("evidence_event_ids", [])
    if isinstance(evidence, str):
        try:
            evidence = [int(x.strip()) for x in evidence.split(",") if x.strip()]
        except Exception:
            evidence = []
    elif not isinstance(evidence, list):
        evidence = []

    explanation = PIIScrubber.redact_text(str(data.get("explanation", "Detected threat indicator.")))

    return AgentDetection(
        tactic=matched_tactic,
        technique_id=str(data.get("technique_id", "T1059")),
        technique_name=str(data.get("technique_name", "Unknown Technique")),
        confidence=min(1.0, max(0.0, conf)),
        evidence_event_ids=evidence,
        explanation=explanation,
        query_used=data.get("query_used"),
    )


class AntigravityAgentHarness(BaseAgentHarness):
    """Google Antigravity hierarchical multi-agent harness powered by Gemini."""

    def __init__(self, model_name: str = "gemini-3.7-flash", thinking_budget: int = 2048):
        """Initialize Google Antigravity hierarchical harness.

        Args:
            model_name (str, optional): Target primary model. Defaults to 'gemini-3.7-flash'.
            thinking_budget (int, optional): Thinking budget for extended reasoning. Defaults to 2048.
        """
        super().__init__(name="Google Antigravity", model_name=model_name, thinking_budget=thinking_budget)
        self.router = ModelRouter()

    def run_investigation(
        self,
        scenario: ScenarioTask,
        sandbox: HarborSandbox,
        use_live_llm: bool = False,
    ) -> AgentTrajectory:
        """Run hierarchical multi-agent threat hunting on scenario telemetry with distributed tracing.

        Args:
            scenario (ScenarioTask): BenchHub threat scenario containing initial alert and ground truth.
            sandbox (HarborSandbox): Active Harbor container sandbox with mounted SQLite telemetry database.
            use_live_llm (bool, optional): If True, invokes live Vertex AI Gemini models. Defaults to False.

        Returns:
            AgentTrajectory: Complete investigative trajectory including step-by-step thoughts, queries, and detections.
        """
        start_time = time.time()
        trajectory_steps: List[HuntStep] = []
        all_detections: List[AgentDetection] = []
        query_count = 0

        skills_registry = SkillsRegistry()
        skills_context = skills_registry.generate_harness_prompt_context()

        if use_live_llm and self.gemini_client.is_live_available():
            system_prompt = (
                f"You are the Google Antigravity Cyber Defense Lead Hunter.\n"
                f"Your goal is to investigate raw SOC telemetry and uncover all MITRE ATT&CK techniques.\n\n"
                f"{skills_context}\n\n"
                f"{sandbox.db.get_schema_summary()}\n\n"
                f"You must respond ONLY with valid JSON conforming to this schema:\n"
                f"{{\n"
                f'  "thought": "Your forensic reasoning process and analysis",\n'
                f'  "action_type": "sql_query" or "submit_findings",\n'
                f'  "sql_query": "SELECT ... FROM events ... (valid SQLite query, omitted if submit_findings)",\n'
                f'  "findings": [\n'
                f"    {{\n"
                f'      "tactic": "initial-access" | "execution" | "persistence" | "privilege-escalation" | "defense-evasion" | "credential-access" | "discovery" | "lateral-movement" | "collection" | "command-and-control" | "exfiltration" | "impact",\n'
                f'      "technique_id": "Txxxx.xxx",\n'
                f'      "technique_name": "Technique Name",\n'
                f'      "confidence": 0.95,\n'
                f'      "evidence_event_ids": [101, 102],\n'
                f'      "explanation": "Why this evidence confirms this technique"\n'
                f"    }}\n"
                f"  ]\n"
                f"}}"
            )

            conversation_history = [
                {
                    "role": "user",
                    "content": (
                        f"Initial Alert Context:\n"
                        f"Scenario: {scenario.title}\n"
                        f"Alert: {scenario.initial_alert}\n"
                        f"Description: {scenario.description}\n\n"
                        f"Begin your multi-agent investigation. Generate the first targeted SQL telemetry query."
                    ),
                }
            ]

            max_turns = 5
            for turn_idx in range(max_turns):
                step_start = time.perf_counter()

                with tracer.start_span(f"antigravity_turn_{turn_idx + 1}", attributes={"turn": turn_idx + 1}):
                    # Strategic Model Routing: Route telemetry queries vs. final synthesis
                    task_complexity = TaskComplexity.CRITICAL_SYNTHESIS if turn_idx >= (max_turns - 1) else TaskComplexity.DEEP_REASONING
                    route_decision = self.router.route(task_complexity, requested_model=self.model_name)

                    raw_response, in_tokens, out_tokens = self.gemini_client.generate_response(
                        system_prompt=system_prompt,
                        conversation_history=conversation_history,
                        model_name=route_decision["model_name"],
                        thinking_budget=route_decision["thinking_budget"],
                    )

                    try:
                        clean_json = raw_response.strip()
                        if clean_json.startswith("```json"):
                            clean_json = clean_json[7:]
                        if clean_json.startswith("```"):
                            clean_json = clean_json[3:]
                        if clean_json.endswith("```"):
                            clean_json = clean_json[:-3]
                        clean_json = clean_json.strip()

                        step_data = json.loads(clean_json)
                    except Exception as parse_err:
                        step_data = {
                            "thought": f"Raw response parsing fallback: {raw_response[:200]}",
                            "action_type": "sql_query",
                            "sql_query": "SELECT id, event_id, process_name, command_line, user FROM process_creation LIMIT 25;",
                            "findings": [],
                        }

                    thought = PIIScrubber.redact_text(step_data.get("thought", "Analyzing telemetry..."))
                    action_type = step_data.get("action_type", "sql_query")
                    sql_query = step_data.get("sql_query")
                    findings_raw = step_data.get("findings", [])

                    step_findings: List[AgentDetection] = []
                    for f in findings_raw:
                        det = normalize_detection(f)
                        if sql_query:
                            det.query_used = sql_query
                        step_findings.append(det)
                        all_detections.append(det)

                    # Execute SQL Action if requested
                    tool_output = None
                    if action_type == "sql_query" and sql_query:
                        query_count += 1
                        with tracer.start_span("execute_sql_query", attributes={"sql": sql_query}):
                            cols, rows, dur_ms, err = sandbox.execute_sql(sql_query, max_rows=30)
                        if err:
                            tool_output = f"SQL Query Error ({dur_ms:.1f}ms): {err}"
                        else:
                            tool_output = f"Columns: {cols}\nReturned {len(rows)} rows:\n" + "\n".join(
                                [str(r) for r in rows[:15]]
                            )

                    step_duration_ms = (time.perf_counter() - step_start) * 1000

                    # Human-in-the-Loop Safety Check for any high-stakes containment action
                    if "isolate" in thought.lower() or "block" in thought.lower():
                        hitl_gate.request_approval(
                            request_id=f"hitl-{scenario.id}-turn{turn_idx+1}",
                            action_type=HighStakesActionType.HOST_ISOLATION,
                            target_resource=scenario.title,
                            proposed_by_agent="Lead Threat Hunter (Antigravity)",
                            justification=thought,
                        )

                    trajectory_step = HuntStep(
                        step_index=turn_idx + 1,
                        agent_role="Lead Threat Hunter (Antigravity)",
                        thought=thought,
                        action_type=action_type,
                        sql_query=sql_query,
                        tool_output=tool_output,
                        new_findings=step_findings,
                        duration_ms=step_duration_ms,
                    )
                    trajectory_steps.append(trajectory_step)

                    logger.info(
                        f"[Antigravity Turn {turn_idx + 1}] Intent: {thought[:80]} | Findings: {len(step_findings)}",
                        extra={"step_index": turn_idx + 1, "intent": thought, "query": sql_query}
                    )

                    if action_type == "submit_findings":
                        break

                    conversation_history.append({"role": "model", "content": raw_response})
                    next_user_content = (
                        f"Tool Execution Output:\n{tool_output}\n\n"
                        f"Evaluate the results against MITRE ATT&CK matrix. Pivot further or submit final findings."
                    )
                    conversation_history.append({"role": "user", "content": next_user_content})

            # Synthesis turn if findings were gathered during query steps
            if not all_detections:
                synthesis_prompt = (
                    f"You are the Forensic Evidence Verifier. Based on your full investigation history:\n"
                    f"Extract and return all confirmed MITRE ATT&CK techniques with evidence event IDs.\n"
                    f"Respond ONLY with a JSON array conforming to the findings schema."
                )
                raw_synth, _, _ = self.gemini_client.generate_response(
                    system_prompt=synthesis_prompt,
                    conversation_history=conversation_history,
                    model_name="gemini-3.7-flash",
                    thinking_budget=2048,
                )
                try:
                    clean_synth = raw_synth.strip()
                    if clean_synth.startswith("```json"):
                        clean_synth = clean_synth[7:]
                    if clean_synth.startswith("```"):
                        clean_synth = clean_synth[3:]
                    if clean_synth.endswith("```"):
                        clean_synth = clean_synth[:-3]
                    synth_data = json.loads(clean_synth.strip())
                    if isinstance(synth_data, list):
                        for f in synth_data:
                            all_detections.append(normalize_detection(f))
                    elif isinstance(synth_data, dict) and "findings" in synth_data:
                        for f in synth_data["findings"]:
                            all_detections.append(normalize_detection(f))
                except Exception:
                    pass

        else:
            # Deterministic simulation mode for offline test verification
            sim_steps = MockCyberHuntingEngine.generate_antigravity_hunt_steps(
                scenario=scenario,
                thinking_budget=self.thinking_budget,
            )

            for step in sim_steps:
                thought = PIIScrubber.redact_text(step.get("thought", ""))
                step_findings = step.get("new_findings", [])
                all_detections.extend(step_findings)

                # If the step specifies a SQL query, execute it in the sandbox
                tool_output = None
                sql_q = step.get("sql_query")
                if sql_q:
                    query_count += 1
                    cols, rows, dur_ms, err = sandbox.execute_sql(sql_q, max_rows=30)
                    if err:
                        tool_output = f"SQL Error: {err}"
                    else:
                        tool_output = f"Returned {len(rows)} rows"

                trajectory_step = HuntStep(
                    step_index=len(trajectory_steps) + 1,
                    agent_role=step.get("agent_role", "Threat Hunter"),
                    thought=thought,
                    action_type=step.get("action_type", "sql_query"),
                    sql_query=sql_q,
                    tool_output=tool_output,
                    new_findings=step_findings,
                    duration_ms=step.get("duration_ms", 120.0),
                )
                trajectory_steps.append(trajectory_step)

        # Deduplicate detections
        deduped: List[AgentDetection] = []
        seen_keys = set()
        for d in all_detections:
            key = (d.tactic.value, d.technique_id)
            if key not in seen_keys:
                seen_keys.add(key)
                deduped.append(d)

        total_duration = (time.time() - start_time) * 1000

        return AgentTrajectory(
            agent_name=self.name,
            model_name=self.model_name,
            thinking_budget=self.thinking_budget,
            total_steps=len(trajectory_steps),
            total_queries=query_count,
            total_tokens_used=len(trajectory_steps) * 600,
            execution_time_seconds=round(total_duration / 1000.0, 2),
            steps=trajectory_steps,
            detected_threats=deduped,
            investigation_summary=f"### Threat Hunt Findings for {scenario.id}\nIdentified {len(deduped)} confirmed techniques.",
        )
